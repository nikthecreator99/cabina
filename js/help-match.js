const EDGE = { б: 'п', в: 'ф', г: 'к', д: 'т', ж: 'ш', з: 'с' };
const VOW = { о: 'а', я: 'а', е: 'и', э: 'и', ы: 'и', ю: 'у', й: 'и' };

// «скелет» слова: как оно звучит, а не как написано
export function skel(w) {
  let s = normSearch(w).replace(/[ъь]/g, '');
  s = s.replace(/[сз]ч/g, 'щ').replace(/т?ся$/, 'ца').replace(/тс/g, 'ц');
  s = s.replace(/[ояеэыюй]/g, (c) => VOW[c]);
  s = s.replace(/(.)\1+/g, '$1');
  const last = s[s.length - 1];
  if (s.length > 2 && EDGE[last]) s = s.slice(0, -1) + EDGE[last];
  return s;
}

const words = (text) => normSearch(text).replace(/<[^>]+>/g, ' ').replace(/[^a-zа-я0-9]+/g, ' ').split(' ').filter(Boolean);

// Дамерау-Левенштейн с ранним выходом (> max — неважно насколько)
function dist(a, b, max) {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...new Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) {
    let row = Infinity;
    for (let j = 1; j <= b.length; j++) {
      const c = a[i - 1] === b[j - 1] ? 0 : 1;
      d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + c);
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) d[i][j] = Math.min(d[i][j], d[i - 2][j - 2] + 1);
      row = Math.min(row, d[i][j]);
    }
    if (row > max) return max + 1;
  }
  return d[a.length][b.length];
}

// насколько слово вопроса q похоже на слово ответа t (оба — скелеты): 0…1; partial — слово ещё печатают
export function wordScore(q, t, partial = false) {
  if (q === t) return 1;
  let p = 0;
  while (p < q.length && p < t.length && q[p] === t[p]) p++;
  const short = Math.min(q.length, t.length);
  const long = Math.max(q.length, t.length);
  // разные окончания одного слова: общее начало — почти всё короткое слово
  if (short >= 3 && p >= 4 && p >= short - 2 && p >= long / 2) return Math.max(0.7, Math.round(95 - 5 * (long - p)) / 100);
  // слово ещё печатают: «счи» → «считается»; совсем короткое начало подходит ко многому — весит меньше
  if (partial && q.length >= 2 && t.startsWith(q)) return q.length >= 4 ? 0.85 : q.length === 3 ? 0.78 : 0.5;
  if (short >= 3 && p >= 3 && short <= 5 && p >= short - 1) return 0.8;
  if (short < 5) return 0;
  // опечатки: слово целиком (длина почти та же) или начало длинного слова (окончание другое)
  const max = short >= 8 ? 2 : 1;
  if (long - short <= max) {
    const dd = dist(q, t, max);
    if (dd <= max) return dd === 1 ? 0.75 : 0.6;
  }
  if (short >= 5) {
    const n = Math.min(short, 7);
    if (dist(q.slice(0, n), t.slice(0, n), 1) <= 1) return 0.65;
  }
  return 0;
}

const FIELDS = [['q', 3], ['k', 2], ['a', 1]];

// индекс: у каждого вопроса — скелеты слов по полям; df — в скольких вопросах встречается скелет
export function buildIndex(items) {
  const docs = items.map((it) => {
    const f = {};
    for (const [name] of FIELDS) f[name] = [...new Set(words(it[name] || '').filter((w) => !STOP.has(w)).map(skel))];
    return { it, f, all: [...new Set([...f.q, ...f.k, ...f.a])] };
  });
  return { docs, n: docs.length };
}

// слова запроса: без пустых, с синонимами; у последнего — признак «ещё печатают»
export function queryTerms(q) {
  const raw = words(q);
  const typing = !/\s$/.test(String(q || ''));
  const out = [];
  raw.forEach((w, i) => {
    const partial = typing && i === raw.length - 1;
    if (STOP.has(w)) return;
    const alts = [...new Set([w, ...(SYN[w] || [])].map(skel))];
    out.push({ w, alts, partial });
  });
  return out;
}

function termScore(term, list) {
  let best = 0;
  for (const t of list) for (const a of term.alts) {
    const s = wordScore(a, t, term.partial);
    if (s > best) { best = s; if (s === 1) return 1; }
  }
  return best;
}

// Подбор: [{ it, score, hit }] по убыванию; score 0…1 — доля «веса» слов запроса, найденная в вопросе.
export function rankHelp(index, q, { limit = 8 } = {}) {
  const terms = queryTerms(q);
  if (!terms.length) return [];
  // редкое слово важнее: вес по тому, у скольких вопросов оно есть
  const idf = terms.map((t) => {
    const df = index.docs.filter((d) => termScore(t, d.all) >= 0.8).length;
    // слова, которого нет ни в одном ответе («скока»), не тянет вниз остальные
    return df ? Math.log(1 + index.n / df) : 0.3;
  });
  const total = idf.reduce((a, b) => a + b, 0) || 1;
  const res = [];
  for (const d of index.docs) {
    let sum = 0; let hit = 0; let strong = false;
    terms.forEach((t, i) => {
      let best = 0;
      for (const [name, wgt] of FIELDS) {
        const s = termScore(t, d.f[name]);
        if (s >= 0.75) strong = true;
        if (s) best = Math.max(best, s * wgt / 3);
      }
      if (best) hit++;
      sum += best * idf[i];
    });
    // хоть одно слово должно совпасть уверенно, а не только «похоже»
    if (!hit || !strong) continue;
    const score = sum / total;
    // слишком мало общего — не предлагаем
    if (score < 0.2) continue;
    res.push({ it: d.it, score, hit });
  }
  res.sort((a, b) => b.score - a.score || b.hit - a.hit);
  // далеко позади лучшего — шум («поезд» в каждом вопросе о поездках), не показываем
  const cut = (res[0]?.score || 0) * 0.4;
  return res.filter((r) => r.score >= cut).slice(0, limit);
}

// Уверенный ответ: лучший заметно лучше остальных и покрывает запрос
export function sureAnswer(ranked) {
  const [a, b] = ranked;
  if (!a || a.score < 0.45) return null;
  if (b && b.score > a.score * 0.85) return null;
  return a;
}

// Текст вопроса с подсвеченными словами, которые совпали с запросом (с учётом опечаток и форм слова).
// Всё, кроме <mark>, экранировано.
export function markText(text, q, esc) {
  const terms = queryTerms(q);
  const src = String(text ?? '');
  if (!terms.length) return esc(src);
  return src.split(/([A-Za-zА-Яа-яЁё0-9]+)/).map((part, i) => {
    if (i % 2 === 0 || STOP.has(normSearch(part))) return esc(part);
    const sk = skel(part);
    return terms.some((t) => termScore(t, [sk]) >= 0.75) ? `<mark>${esc(part)}</mark>` : esc(part);
  }).join('');
}
