const out = join(dirname(fileURLToPath(import.meta.url)), 'info');
mkdirSync(out, { recursive: true });
let left = 0;
for (const [name, html] of Object.entries(pages)) {
  writeFileSync(join(out, name), html);
  left += (html.match(/\[ЗАПОЛНИТЬ:/g) || []).length;
}
console.log(`Собрано страниц: ${Object.keys(pages).length}, не заполнено мест: ${left} (политика от ${POLICY_DATE}, адрес страниц ${PAGE})`);
if (process.argv.includes('--check') && left) process.exit(1);
